local Module = {}

------------------------------------------------------------
-- Module Identity
--
-- 必须全局唯一。
------------------------------------------------------------

Module.id =
    "EXAMPLE_MODULE"

------------------------------------------------------------
-- Main Menu Entry
--
-- 如果模块不需要出现在主菜单，
-- 可以完全删除 Module.menu。
------------------------------------------------------------

Module.menu = {
    --------------------------------------------------------
    -- 主菜单显示名称
    --------------------------------------------------------

    label =
        "EXAMPLE",

    --------------------------------------------------------
    -- ENTER 后进入的页面
    --
    -- 必须是 createPages() 注册的页面之一。
    --------------------------------------------------------

    page =
        "EXAMPLE_MAIN",

    --------------------------------------------------------
    -- 主菜单排序
    --
    -- 数字越小越靠前。
    --------------------------------------------------------

    order =
        100,
}

------------------------------------------------------------
-- Create Pages
------------------------------------------------------------

function Module.createPages(context)

    --------------------------------------------------------
    -- Load module-owned page class
    --------------------------------------------------------

    local ExamplePage =
        context:load(
            "ExamplePage.lua"
        )

    if
        type(ExamplePage) ~= "table" or
        type(ExamplePage.new) ~= "function"
    then
        error(
            "Invalid ExamplePage.lua"
        )
    end

    --------------------------------------------------------
    -- Optional module assets
    --
    -- 使用时取消注释：
    --
    -- local imagePath =
    --     context:asset(
    --         "Images\\example.png"
    --     )
    --------------------------------------------------------

    --------------------------------------------------------
    -- Register all pages owned by this module
    --------------------------------------------------------

    return {
        EXAMPLE_MAIN =
            ExamplePage.new({
                aircraftData =
                    context.aircraftData,

                -- imagePath =
                --     imagePath,
            }),
    }
end

return Module